/**
 * A template as a ready-to-run `.zip` (0.3.0 phase 13).
 *
 * The compose file, a README, and whatever sources the template ships —
 * assembled in the browser through [zip.ts](../zip.ts), because an archive
 * built on a server would need a server.
 *
 * The README is generated from the template rather than written per template:
 * it can then state the pinned tags as facts read out of the model, and those
 * cannot drift from what the compose file actually says.
 */
import { zipBlob, type ZipEntry } from '../zip';
import { emitCompose } from './emit';
import type { ComposeProjectModel } from './model';
import type { StackTemplate } from './templates';

/** The README shipped beside the compose file. */
export function readmeFor(template: StackTemplate, project: ComposeProjectModel): string {
  const lines: string[] = [
    `# ${template.label}`,
    '',
    template.note,
    '',
    '## Run it',
    '',
    '```sh',
    'docker compose up',
    '```',
    '',
  ];

  if (template.steps && template.steps.length > 0) {
    lines.push('## First, scaffold the app', '', ...template.steps, '');
  }

  const ports = project.services
    .flatMap((s) => s.ports.filter((p) => p.published.trim() !== '').map((p) => ({ service: s.name, port: p.published })))
    .map((p) => `- **${p.service}** — http://localhost:${p.port}`);
  if (ports.length > 0) lines.push('## Where it lands', '', ...ports, '');

  const env = project.services.flatMap((s) =>
    s.environment.filter((e) => /\$\{[^}]+\}/.test(e.value)).map((e) => `- \`${e.key}\` — ${e.value}`)
  );
  if (env.length > 0) {
    lines.push(
      '## Environment',
      '',
      'These read from your shell or a `.env` file beside the compose file:',
      '',
      ...[...new Set(env)],
      ''
    );
  }

  lines.push(
    '## The image tags',
    '',
    'Pinned as of the day this was generated:',
    '',
    ...template.pins.map((pin) => `- \`${pin}\``),
    '',
    '**Tags move.** `:16-alpine` picks up security updates under the same name, and a major',
    'version bump one day becomes something nobody tested this against. Check them before',
    'you rely on this in anything that matters, and pin by digest if you need it frozen.',
    '',
    '---',
    '',
    'Generated by the Docker Compose builder in `useful`. Nothing was uploaded to make it.',
    ''
  );

  return lines.join('\n');
}

/** Every entry the archive holds, in the order a person would read them. */
export function archiveEntries(template: StackTemplate, project: ComposeProjectModel): ZipEntry[] {
  return [
    { name: 'compose.yaml', data: emitCompose(project) },
    { name: 'README.md', data: readmeFor(template, project) },
    ...(template.files ?? []).map((file) => ({ name: file.name, data: file.content })),
  ];
}

export function archiveBlob(template: StackTemplate, project: ComposeProjectModel): Blob {
  return zipBlob(archiveEntries(template, project));
}

export const archiveName = (template: StackTemplate): string => `${template.id}-compose.zip`;
