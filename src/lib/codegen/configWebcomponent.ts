/**
 * A config schema as a dependency-free custom element.
 *
 * Two flavours, one file each. The **parser** takes a pasted document, checks
 * it against the schema on every keystroke, and surfaces each field's value.
 * The **generator** takes a count and a plain button and produces that many
 * sample documents. Both are droppable into any page: no build step, no
 * framework, no CDN reference — the no-CDN rule applies to what the app
 * produces, not only what it loads.
 *
 * The validation and generation logic is not written here. It comes from the
 * one exported CONFIG_JS_RUNTIME table in config.ts, so a component and the
 * four-language emitters never drift apart on what "valid" means.
 *
 * Styling is deliberately almost absent: every element carries a `part`
 * attribute and nothing else, so the host page styles it with `::part()` and
 * has nothing to override.
 *
 * One honest limit, stated in the component's own header and on its face: the
 * parser accepts **JSON input only**. A dependency-free file cannot parse
 * YAML, and pretending otherwise would be a parser that silently wasn't one.
 */
import type { ConfigField } from '../db/types';
import { CONFIG_JS_RUNTIME, type ConfigCodeTemplate, type ConfigFlavor } from './config';

/** Escape for an HTML text node or a double-quoted attribute value. */
const escapeHtml = (text: string): string =>
  text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

/** Neutralise anything in free text that could close the comment it sits in. */
const commentSafe = (text: string): string =>
  text
    .replace(/\r?\n/g, ' ')
    .replace(/\*\//g, '*​/')
    .trim();

/**
 * A schema name plus its flavour as a custom-element tag: `deploy-settings`
 * becomes `deploy-settings-parser`. The flavour suffix is what guarantees the
 * hyphen a custom-element name must contain; a name that is empty or starts
 * with a digit gets a `config-` prefix so the tag starts with a letter.
 */
export function configTagName(name: string, flavor: ConfigFlavor): string {
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  const base = slug && /^[a-z]/.test(slug) ? slug : `config${slug ? '-' + slug : ''}`;
  return `${base}-${flavor}`;
}

/** `deploy-settings-parser` -> `DeploySettingsParser`, for the class name. */
const className = (tag: string): string =>
  tag
    .split('-')
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('');

/** Emit the component for one schema and flavour. */
export function generateConfigWebComponent(
  template: ConfigCodeTemplate,
  flavor: ConfigFlavor,
): string {
  const tag = configTagName(template.name, flavor);
  const cls = className(tag);
  const name = template.name.trim() || 'config';
  const fields: ConfigField[] = JSON.parse(JSON.stringify(template.fields)) as ConfigField[];

  const header = [
    '/**',
    ` * <${tag}> — ${flavor === 'parser' ? 'validates a' : 'generates sample'} “${commentSafe(name)}” ${flavor === 'parser' ? 'document (JSON) against its schema' : 'documents from its schema'}.`,
    ' *',
    ' * Generated by the config playground. Dependency-free: no imports, no',
    ' * network, no CSS opinions. Drop it in with',
    ' *',
    ` *   <script type="module" src="${tag}.js"></script>`,
    ` *   <${tag}></${tag}>`,
    ' *',
    ' * and style it from the outside through parts, for example',
    ' *',
    ...(flavor === 'parser'
      ? [
          ` *   ${tag}::part(textarea) { width: 100%; font-family: monospace; }`,
          ` *   ${tag}::part(issue)[data-severity="error"] { color: crimson; }`,
          ' *',
          ' * It accepts JSON input only. A file with no dependencies cannot parse',
          ' * YAML — decode YAML to JSON first, or use the generated Python/Go code.',
          ' *',
          " * Fires 'config-valid' after every input, with { value, issues } in",
          ' * detail: `value` is the parsed document (or null) and `issues` the',
          ' * problems found ({ path, message, severity }).',
        ]
      : [
          ` *   ${tag}::part(output) { font-family: monospace; white-space: pre; }`,
          ` *   ${tag}::part(button) { font: inherit; }`,
          ' *',
          ' * Set a `seed` attribute for reproducible documents; without one every',
          ' * press produces a fresh batch.',
          ' *',
          " * Fires 'config-generated' after every press, with { documents } in",
          ' * detail.',
        ]),
    ' */',
  ];

  const runtime =
    flavor === 'parser'
      ? [CONFIG_JS_RUNTIME.formats, '', CONFIG_JS_RUNTIME.validate]
      : [
          CONFIG_JS_RUNTIME.prng,
          '',
          CONFIG_JS_RUNTIME.words,
          '',
          CONFIG_JS_RUNTIME.generate,
          ...(template.format === 'yaml' ? ['', CONFIG_JS_RUNTIME.toYaml] : []),
        ];

  const body = flavor === 'parser' ? parserClass(cls, template.format) : generatorClass(cls, template.format);

  return [
    ...header,
    `const FIELDS = ${JSON.stringify(fields)};`,
    '',
    ...runtime,
    '',
    'function _escape(text) {',
    '  return String(text)',
    "    .replace(/&/g, '&amp;')",
    "    .replace(/</g, '&lt;')",
    "    .replace(/>/g, '&gt;')",
    "    .replace(/\"/g, '&quot;');",
    '}',
    '',
    ...body,
    '',
    `customElements.define(${JSON.stringify(tag)}, ${cls});`,
    '',
  ].join('\n');
}

/** The shadow-root markup for the parser, as an escaped JS string literal. */
function parserMarkup(format: 'json' | 'yaml'): string {
  const note =
    format === 'yaml'
      ? '<p part="note">This schema is YAML, but this component accepts <strong>JSON</strong> input only — decode the YAML first.</p>'
      : '';
  return JSON.stringify(
    '<div part="root">' +
      note +
      '<label part="label">Document<textarea part="textarea" rows="10" spellcheck="false"></textarea></label>' +
      '<p part="status" data-state="empty"></p>' +
      '<ul part="issues"></ul>' +
      '<table part="table"><thead><tr><th part="heading">Field</th><th part="heading">Type</th><th part="heading">Value</th></tr></thead><tbody part="rows"></tbody></table>' +
      '</div>',
  );
}

function parserClass(cls: string, format: 'json' | 'yaml'): string[] {
  return [
    `class ${cls} extends HTMLElement {`,
    '  constructor() {',
    '    super();',
    "    this.attachShadow({ mode: 'open' });",
    `    this.shadowRoot.innerHTML = ${parserMarkup(format)};`,
    "    this._textarea = this.shadowRoot.querySelector('textarea');",
    "    this._status = this.shadowRoot.querySelector('[part=\"status\"]');",
    "    this._issues = this.shadowRoot.querySelector('[part=\"issues\"]');",
    "    this._rows = this.shadowRoot.querySelector('[part=\"rows\"]');",
    "    this._textarea.addEventListener('input', () => this.check());",
    '  }',
    '',
    '  /** The document to check; setting it is the same as pasting it. */',
    '  get value() {',
    '    return this._textarea.value;',
    '  }',
    '',
    '  set value(text) {',
    "    this._textarea.value = text == null ? '' : String(text);",
    '    this.check();',
    '  }',
    '',
    '  check() {',
    '    const text = this._textarea.value;',
    "    this._issues.innerHTML = '';",
    "    this._rows.innerHTML = '';",
    '    if (text.trim() === \'\') {',
    "      this._status.textContent = '';",
    "      this._status.dataset.state = 'empty';",
    "      this._emit(null, []);",
    '      return;',
    '    }',
    '    let data;',
    '    try {',
    '      data = JSON.parse(text);',
    '    } catch (err) {',
    "      this._status.textContent = 'Not valid JSON: ' + (err && err.message ? err.message : String(err));",
    "      this._status.dataset.state = 'invalid';",
    "      this._emit(null, [{ path: '', message: 'not valid JSON', severity: 'error' }]);",
    '      return;',
    '    }',
    '    // An array is a set of documents, each checked on its own.',
    '    const issues = Array.isArray(data)',
    '      ? data.flatMap((item, i) =>',
    "          _validate(item, FIELDS).map((issue) => ({ ...issue, path: '[' + i + ']' + (issue.path ? '.' + issue.path : '') }))",
    '        )',
    '      : _validate(data, FIELDS);',
    "    const errors = issues.filter((issue) => issue.severity === 'error');",
    '    this._status.textContent = errors.length === 0',
    "      ? 'Valid'",
    "      : errors.length + (errors.length === 1 ? ' problem' : ' problems');",
    "    this._status.dataset.state = errors.length === 0 ? 'valid' : 'invalid';",
    '    for (const issue of issues) {',
    "      const li = document.createElement('li');",
    "      li.setAttribute('part', 'issue');",
    '      li.dataset.severity = issue.severity;',
    "      li.textContent = (issue.path || 'document') + ' — ' + issue.message;",
    '      this._issues.append(li);',
    '    }',
    '    const first = Array.isArray(data) ? data[0] : data;',
    "    if (first && typeof first === 'object' && !Array.isArray(first)) {",
    '      for (const field of FIELDS) {',
    "        const tr = document.createElement('tr');",
    "        tr.setAttribute('part', 'row');",
    '        const present = Object.prototype.hasOwnProperty.call(first, field.key);',
    "        tr.innerHTML = '<td part=\"cell\">' + _escape(field.key) + '</td><td part=\"cell\">' + _escape(_label(field.type)) + '</td><td part=\"cell\">' + (present ? _escape(JSON.stringify(first[field.key])) : '<em>absent</em>') + '</td>';",
    '        this._rows.append(tr);',
    '      }',
    '    }',
    '    this._emit(data, issues);',
    '  }',
    '',
    '  _emit(value, issues) {',
    "    this.dispatchEvent(new CustomEvent('config-valid', { detail: { value, issues }, bubbles: true, composed: true }));",
    '  }',
    '}',
    '',
    '/** The Type column: `Array[string]`, `enum(dev | prod)`, `object`, … */',
    'function _label(type) {',
    "  if (type.kind === 'array') return 'Array[' + (type.item ? _label(type.item) : 'any') + ']';",
    "  if (type.kind === 'enum') return 'enum(' + (type.values || []).map(String).join(' | ') + ')';",
    "  if (type.kind === 'union') return (type.variants || []).map(_label).join(' | ') || 'any';",
    '  return type.kind;',
    '}',
  ];
}

/** The shadow-root markup for the generator, as an escaped JS string literal. */
function generatorMarkup(): string {
  return JSON.stringify(
    '<div part="root">' +
      '<label part="label">How many<input part="input" type="number" min="1" max="100" step="1" value="3"></label>' +
      '<button part="button" type="button">Generate</button>' +
      '<pre part="output"></pre>' +
      '</div>',
  );
}

function generatorClass(cls: string, format: 'json' | 'yaml'): string[] {
  return [
    `class ${cls} extends HTMLElement {`,
    '  constructor() {',
    '    super();',
    "    this.attachShadow({ mode: 'open' });",
    `    this.shadowRoot.innerHTML = ${generatorMarkup()};`,
    "    this._count = this.shadowRoot.querySelector('input');",
    "    this._output = this.shadowRoot.querySelector('[part=\"output\"]');",
    "    this.shadowRoot.querySelector('button').addEventListener('click', () => this.generate());",
    '  }',
    '',
    '  /** Produce the documents; also what the button does. */',
    '  generate() {',
    '    const count = Math.max(1, Math.min(100, Math.floor(Number(this._count.value) || 1)));',
    '    this._count.value = String(count);',
    "    const attr = this.getAttribute('seed');",
    "    const seed = attr !== null && attr !== '' && Number.isFinite(Number(attr))",
    '      ? Number(attr) >>> 0',
    '      : (Math.random() * 0xffffffff) >>> 0;',
    '    const documents = _generate(FIELDS, count, seed);',
    ...(format === 'yaml'
      ? ["    this._output.textContent = documents.map((doc) => _toYaml(doc)).join('\\n---\\n');"]
      : [
          '    this._output.textContent = JSON.stringify(documents.length === 1 ? documents[0] : documents, null, 2);',
        ]),
    "    this.dispatchEvent(new CustomEvent('config-generated', { detail: { documents, seed }, bubbles: true, composed: true }));",
    '    return documents;',
    '  }',
    '}',
  ];
}
